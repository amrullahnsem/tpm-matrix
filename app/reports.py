def department_competency_report(
    repo: Repository,
    department: str,
    output_dir: Path = DEFAULT_OUTPUT,
    *,
    fmt: tuple[str, ...] = ("pdf", "xlsx"),
) -> ReportArtifact:
    employees = repo.list_employees(department=department)
    summary = repo.department_summary(department)
    output_dir.mkdir(parents=True, exist_ok=True)
    stem = f"02_department_{department.replace(' ', '_').replace('&', 'and')}"

    headers = ["Employee No.", "Name", "Position", "Supervisor", "Exp.", "Overall %", "Assessed", "Coverage %", "Gaps"]
    rows: list[list[object]] = []
    for employee in employees:
        _, overall, gaps = repo.build_matrix(employee.id)
        rows.append(
            [
                employee.employee_number,
                employee.full_name,
                employee.position_title,
                employee.supervisor or "-",
                f"{employee.years_of_experience}y" if employee.years_of_experience is not None else "-",
                f"{overall.percentage:.1f}%",
                f"{overall.assessed_count}/{overall.total_count}",
                f"{overall.coverage_percentage:.1f}%",
                str(sum(1 for g in gaps if g.status is GapStatus.GAP)),
            ]
        )
    rows.sort(key=lambda r: float(str(r[5]).rstrip("%")), reverse=True)

    # Competency x position average, to expose which axes the team lacks.
    axis_rows: list[list[object]] = []
    totals: dict[str, list[int]] = {}
    names: dict[str, str] = {}
    for employee in employees:
        scores, _, _ = repo.build_matrix(employee.id)
        for score in scores:
            if score.required_score <= 0 or score.rating_score is None:
                continue
            totals.setdefault(score.competency_id, []).append(score.rating_score)
            names[score.competency_id] = score.competency_name
    for competency_id, ratings in totals.items():
        axis_rows.append(
            [
                names[competency_id],
                len(ratings),
                f"{sum(ratings) / len(ratings):.2f}",
                f"{(sum(ratings) / len(ratings)) * 20:.1f}%",
            ]
        )
    axis_rows.sort(key=lambda r: float(str(r[2])), reverse=True)

    pdf_path: Path | None = None
    if "pdf" in fmt:
        styles = _styles()
        story = _pdf_header(
            "Department Competency Report",
            f"{department} - {summary.employee_count} employees - generated {dt.date.today().isoformat()}",
            styles,
        )
        story.append(
            _pdf_table(
                ["Metric", "Value"],
                [
                    ["Employees", summary.employee_count],
                    ["Average overall competency", f"{summary.average_percentage:.1f}%"],
                    ["Highest / Lowest", f"{summary.maximum_percentage:.1f}% / {summary.minimum_percentage:.1f}%"],
                    ["Competencies achieved", summary.achieved_count],
                    ["Competencies with a gap", summary.gap_count],
                    ["Competencies not yet assessed", summary.unassessed_count],
                    ["Critical action items", summary.critical_gap_count],
                ],
                widths=[70 * mm, 80 * mm],
            )
        )
        story.append(Paragraph("Employees by Overall Competency", styles["h2"]))
        story.append(
            _pdf_table(
                headers,
                rows or [["-"] * len(headers)],
                widths=[24 * mm, 40 * mm, 45 * mm, 38 * mm, 12 * mm, 18 * mm, 18 * mm, 20 * mm, 14 * mm],
            )
        )
        story.append(Paragraph("Team Average by Competency (weakest first)", styles["h2"]))
        story.append(
            _pdf_table(
                ["Competency", "Staff Assessed", "Avg Rating", "Avg %"],
                axis_rows or [["-"] * 4],
                widths=[95 * mm, 25 * mm, 25 * mm, 25 * mm],
            )
        )
        pdf_path = _write_pdf(output_dir / f"{stem}.pdf", story, landscape_mode=True)

    xlsx_path: Path | None = None
    if "xlsx" in fmt:
        xlsx_path = _write_workbook(
            output_dir / f"{stem}.xlsx",
            {
                "Summary": (
                    ["Metric", "Value"],
                    [
                        ["Department", department],
                        ["Employees", summary.employee_count],
                        ["Average %", summary.average_percentage],
                        ["Minimum %", summary.minimum_percentage],
                        ["Maximum %", summary.maximum_percentage],
                        ["Achieved", summary.achieved_count],
                        ["Gaps", summary.gap_count],
                        ["Unassessed", summary.unassessed_count],
                        ["Critical", summary.critical_gap_count],
                    ],
                ),
                "Employees": (headers, rows),
                "Competency Averages": (["Competency", "Staff Assessed", "Avg Rating", "Avg %"], axis_rows),
            },
        )

    return ReportArtifact(
        name="department_competency_report",
        title=f"Department Competency Report - {department}",
        pdf=pdf_path,
        xlsx=xlsx_path,
        row_count=len(rows),
    )


