# ---------------------------------------------------------------------------

def competency_gap_report(
    repo: Repository,
    output_dir: Path = DEFAULT_OUTPUT,
    *,
    department: str | None = None,
    fmt: tuple[str, ...] = ("pdf", "xlsx"),
) -> ReportArtifact:
    records = repo.training_needs(department=department)
    output_dir.mkdir(parents=True, exist_ok=True)
    stem = f"03_competency_gap_{department.replace(' ', '_') if department else 'all'}"

    headers = ["Priority", "Employee No.", "Name", "Position", "Competency", "Category", "Req.", "Cur.", "Short.", "Status"]
    rows = [
        [
            r["priority"],
            r["employeeNumber"],
            r["employeeName"],
            r["positionTitle"],
            r["competencyName"],
            r["category"],
            r["requiredScore"],
            _fmt_rating(r["ratingScore"]),  # type: ignore[arg-type]
            r["shortfall"],
            r["status"],
        ]
        for r in records
    ]

    counts = {str(p): 0 for p in Priority}
    for record in records:
        counts[str(record["priority"])] = counts.get(str(record["priority"]), 0) + 1

    pdf_path: Path | None = None
    if "pdf" in fmt:
        styles = _styles()
        story = _pdf_header(
            "Competency Gap Report",
            f"Scope: {department or 'All departments'} - {len(records)} action items - "
            f"generated {dt.date.today().isoformat()}",
            styles,
        )
        story.append(
            _pdf_table(
                ["Priority Band", "Count"],
                [[priority, counts.get(priority, 0)] for priority in ("Critical", "High", "Medium", "Low")],
                widths=[50 * mm, 30 * mm],
            )
        )
        story.append(Paragraph("All Competency Gaps (most urgent first)", styles["h2"]))
        story.append(
            _pdf_table(
                headers,
                rows or [["-"] * len(headers)],
                widths=[19 * mm, 22 * mm, 38 * mm, 40 * mm, 55 * mm, 26 * mm, 12 * mm, 14 * mm, 13 * mm, 20 * mm],
            )
        )
        pdf_path = _write_pdf(output_dir / f"{stem}.pdf", story, landscape_mode=True)

    xlsx_path: Path | None = None
    if "xlsx" in fmt:
        xlsx_path = _write_workbook(
            output_dir / f"{stem}.xlsx", {"Competency Gaps": (headers, rows)}
        )

    return ReportArtifact(
        name="competency_gap_report",
        title="Competency Gap Report",
        pdf=pdf_path,
        xlsx=xlsx_path,
        row_count=len(rows),
    )


