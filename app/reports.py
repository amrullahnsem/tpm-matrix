def individual_competency_report(
    repo: Repository,
    employee_id: str,
    output_dir: Path = DEFAULT_OUTPUT,
    *,
    fmt: tuple[str, ...] = ("pdf", "xlsx"),
) -> ReportArtifact:
    profile = repo.get_profile(employee_id)
    employee = profile.employee
    output_dir.mkdir(parents=True, exist_ok=True)
    stem = f"01_individual_{employee.employee_number.replace('/', '-')}"

    header_cells = [
        ["Employee", employee.full_name],
        ["Employee No.", employee.employee_number],
        ["Position", employee.position_title],
        ["Department", employee.department],
        ["Supervisor", employee.supervisor or "-"],
        ["Date Joined", f"{employee.join_date} ({employee.years_of_experience}y)"],
        [
            "Overall Competency",
            f"{profile.overall.percentage:.1f}%  "
            f"({profile.overall.total_rating}/{profile.overall.max_possible_rating})",
        ],
        [
            "Assessment Coverage",
            f"{profile.overall.assessed_count}/{profile.overall.total_count} assessed "
            f"({profile.overall.coverage_percentage:.1f}%)",
        ],
    ]

    matrix_rows = [
        [
            gap.competency_name,
            gap.category,
            _fmt_rating(gap.rating_score),
            _fmt_rating(gap.required_score),
            _fmt_pct(gap.current_percentage),
            f"{gap.required_percentage}%",
            str(gap.status),
            str(gap.priority) if gap.is_actionable else "-",
            str(gap.shortfall) if gap.is_actionable else "0",
        ]
        for gap in profile.gaps
    ]
    matrix_headers = [
        "Competency",
        "Category",
        "Current",
        "Required",
        "Current %",
        "Required %",
        "Status",
        "Priority",
        "Shortfall",
    ]

    history_rows = [
        [
            a.assessment_date,
            a.cycle_name,
            a.assessor_name,
            f"{a.total_rating}/{a.max_possible_rating}",
            f"{a.overall_percentage:.1f}%",
            a.remarks or "",
        ]
        for a in profile.assessments
    ]
    training_rows = [
        [t.completion_date, t.title, t.provider or "", t.status, t.reassessment_cycle or ""]
        for t in profile.training
    ]

    pdf_path: Path | None = None
    if "pdf" in fmt:
        styles = _styles()
        available_width = landscape(A4)[0] - 30 * mm
        story = _pdf_header(
            "Individual Competency Report",
            f"{employee.full_name} - {employee.position_title} - generated {dt.date.today().isoformat()}",
            styles,
        )
        story.append(_pdf_table(["Field", "Value"], header_cells, widths=[45 * mm, available_width - 45 * mm]))
        story.append(Spacer(1, 8))

        story.append(Paragraph("Competency Spider Chart", styles["h2"]))
        drawing = _svg_drawing(profile, max_width=available_width, max_height=150 * mm)
        if drawing is not None:
            story.append(drawing)
            story.append(Spacer(1, 4))
            story.append(
                Paragraph(
                    "Solid blue polygon = current competency. Dashed amber polygon = level "
                    "required for the position. A break in the blue polygon marks a "
                    "competency that has not yet been assessed (not a score of zero).",
                    styles["small"],
                )
            )
            story.append(Spacer(1, 8))

        story.append(
            KeepTogether(
                [
                    Paragraph("Competency Matrix", styles["h2"]),
                    _pdf_table(
                        matrix_headers,
                        matrix_rows,
                        widths=[62 * mm, 26 * mm, 17 * mm, 17 * mm, 17 * mm, 19 * mm, 20 * mm, 19 * mm, 16 * mm],
                        status_colour={6: colors.HexColor("#333333")},
                    ),
                ]
            )
        )

        story.append(Paragraph("Assessment History", styles["h2"]))
        story.append(
            _pdf_table(
                ["Date", "Cycle", "Assessor", "Score", "Overall", "Remarks"],
                history_rows or [["-"] * 6],
                widths=[22 * mm, 42 * mm, 32 * mm, 18 * mm, 16 * mm, 87 * mm],
            )
        )
        story.append(Paragraph("Training History", styles["h2"]))
        story.append(
            _pdf_table(
                ["Completed", "Training", "Provider", "Status", "Reassessment Cycle"],
                training_rows or [["-"] * 5],
                widths=[22 * mm, 62 * mm, 42 * mm, 20 * mm, 71 * mm],
            )
        )
        pdf_path = _write_pdf(output_dir / f"{stem}.pdf", story, landscape_mode=True)

    xlsx_path: Path | None = None
    if "xlsx" in fmt:
        xlsx_path = _write_workbook(
            output_dir / f"{stem}.xlsx",
            {
                "Summary": (["Field", "Value"], header_cells),
                "Competency Matrix": (matrix_headers, matrix_rows),
                "Assessment History": (
                    ["Assessment Date", "Cycle", "Assessor", "Score", "Overall %", "Remarks"],
                    history_rows,
                ),
                "Training History": (
                    ["Completion Date", "Training", "Provider", "Status", "Reassessment Cycle"],
                    training_rows,
                ),
            },
        )

    return ReportArtifact(
        name="individual_competency_report",
        title=f"Individual Competency Report - {employee.full_name}",
        pdf=pdf_path,
        xlsx=xlsx_path,
        row_count=len(matrix_rows),
    )


def _svg_drawing(profile, *, max_width: float, max_height: float):
    """Convert the spider-chart SVG into a ReportLab Drawing that fits the frame."""
    import io

    svg = render_radar_svg(profile.scores, size=1000, employee_name=profile.employee.full_name)
    drawing = svg2rlg(io.BytesIO(svg.encode("utf-8")))
    if drawing is None:
        return None
    scale = min(max_width / drawing.width, max_height / drawing.height)
    drawing.width *= scale
    drawing.height *= scale
    drawing.scale(scale, scale)
    return drawing


