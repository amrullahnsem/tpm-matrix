# ---------------------------------------------------------------------------
# Report 5 - Competency Progress Report
# ---------------------------------------------------------------------------

def competency_progress_report(
    repo: Repository,
    employee_id: str,
    output_dir: Path = DEFAULT_OUTPUT,
    *,
    fmt: tuple[str, ...] = ("pdf", "xlsx"),
) -> ReportArtifact:
    profile = repo.get_profile(employee_id)
    history = repo.progress_history(employee_id)
    output_dir.mkdir(parents=True, exist_ok=True)
    stem = f"05_progress_{profile.employee.employee_number.replace('/', '-')}"

    headers = ["Date", "Cycle", "Assessor", "Total", "Max", "Overall %", "Change", "Per-competency detail"]
    rows: list[list[object]] = []
    for entry in history:
        delta = entry["deltaPercentage"]
        rows.append(
            [
                entry["assessmentDate"],
                entry["cycleName"],
                entry["assessorName"],
                entry["totalRating"],
                entry["maxPossibleRating"],
                f"{entry['overallPercentage']:.1f}%",
                "-" if delta is None else f"{delta:+.1f} pts",
                "Yes" if entry["hasPerCompetencyDetail"] else "No",
            ]
        )

    movement_rows: list[list[object]] = []
    first, latest = (history[0], history[-1]) if len(history) >= 2 else (None, None)
    if first and latest:
        for score in profile.scores:
            movement_rows.append(
                [
                    score.competency_name,
                    score.category,
                    _fmt_rating(score.rating_score),
                    score.required_score,
                    _fmt_pct(score.current_percentage),
                    score.shortfall,
                    str(assess_status(score.rating_score, score.required_score)),
                ]
            )

    caveat = ""
    if history and not all(entry["hasPerCompetencyDetail"] for entry in history):
        caveat = (
            "Note: some assessment cycles were recorded before per-competency detail was "
            "captured, so trend movement can only be shown at the overall-percentage level "
            "for those cycles. Re-assess to restore per-competency trending."
        )

    pdf_path: Path | None = None
    if "pdf" in fmt:
        styles = _styles()
        story = _pdf_header(
            "Competency Progress Report",
            f"{profile.employee.full_name} - {profile.employee.position_title} - "
            f"generated {dt.date.today().isoformat()}",
            styles,
        )
        story.append(Paragraph("Assessment Trend", styles["h2"]))
        story.append(
            _pdf_table(
                headers,
                rows or [["-"] * len(headers)],
                widths=[22 * mm, 44 * mm, 32 * mm, 14 * mm, 14 * mm, 20 * mm, 20 * mm, 40 * mm],
            )
        )
        if caveat:
            story.append(Spacer(1, 6))
            story.append(Paragraph(caveat, styles["small"]))
        if movement_rows:
            story.append(Paragraph("Current Standing by Competency", styles["h2"]))
            story.append(
                _pdf_table(
                    ["Competency", "Category", "Current", "Required", "Current %", "Shortfall", "Status"],
                    movement_rows,
                    widths=[68 * mm, 30 * mm, 20 * mm, 20 * mm, 20 * mm, 20 * mm, 28 * mm],
                )
            )
        pdf_path = _write_pdf(output_dir / f"{stem}.pdf", story, landscape_mode=True)

    xlsx_path: Path | None = None
    if "xlsx" in fmt:
        xlsx_path = _write_workbook(
            output_dir / f"{stem}.xlsx",
            {
                "Progress Trend": (headers, rows),
                "Current Standing": (
                    ["Competency", "Category", "Current", "Required", "Current %", "Shortfall", "Status"],
                    movement_rows,
                ),
            },
        )

    return ReportArtifact(
        name="competency_progress_report",
        title=f"Competency Progress Report - {profile.employee.full_name}",
        pdf=pdf_path,
        xlsx=xlsx_path,
        row_count=len(rows),
    )


def assess_status(rating: int | None, required: int) -> str:
    if rating is None:
        return str(GapStatus.UNASSESSED)
    return str(GapStatus.ACHIEVED if rating >= required else GapStatus.GAP)
