"""PDF and Excel report generation for the TPM Competency Matrix.

Libraries used
--------------
* **PDF**  - ``reportlab`` (pure Python, no system dependency) with
  ``svglib`` to embed the spider chart generated by :mod:`app.radar`. The
  chart is produced by our own code and converted to a ReportLab
  ``Drawing``, so the printed report and the on-screen dashboard share one
  geometry implementation and can never drift apart.
* **Excel** - ``openpyxl``.

If you later prefer a different toolchain, the substitution points are
narrow: :func:`_write_pdf` and :func:`_write_workbook` are the only places
that touch either library. See ``docs/REPORTING.md`` for alternatives
(xlsxwriter, WeasyPrint/Chromium for HTML->PDF, Tabulator, etc.).

All five required reports are produced by this module:
    1. individual_competency_report   (includes the spider chart)
    2. department_competency_report
    3. competency_gap_report
    4. training_needs_report
    5. competency_progress_report
"""

